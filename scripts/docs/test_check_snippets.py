"""Tests of check_snippets.py. Run with: python3 -m unittest discover -s scripts/docs"""
import tempfile
import unittest
from pathlib import Path

import _snippets
import check_snippets as checker


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


class CheckTest(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.docs = Path(self.tmp.name) / "docs"
        self.examples = self.docs / "examples"
        self.examples.mkdir(parents=True)
        self._real_examples = _snippets.EXAMPLES
        _snippets.EXAMPLES = self.examples
        self.addCleanup(self._restore)

    def _restore(self):
        _snippets.EXAMPLES = self._real_examples

    def test_a_block_matching_its_source_has_no_problem(self):
        write(self.examples / "e" / "steps.sh", "# region: a\nslay400 init\n# endregion\n")
        page = write(self.docs / "guides" / "g" / "index.md",
                     "<!-- snippet: examples/e/steps.sh#a -->\n```sh\nslay400 init\n```\n")
        self.assertEqual([], checker.check(write=False, root=self.docs))

    def test_a_mismatched_block_is_reported(self):
        write(self.examples / "e" / "steps.sh", "# region: a\nslay400 init\n# endregion\n")
        write(self.docs / "guides" / "g" / "index.md",
              "<!-- snippet: examples/e/steps.sh#a -->\n```sh\nslay400 wrong\n```\n")
        problems = checker.check(write=False, root=self.docs)
        self.assertEqual(1, len(problems))
        self.assertIn("does not match its source", problems[0])

    def test_write_corrects_a_mismatched_block_in_place(self):
        write(self.examples / "e" / "steps.sh", "# region: a\nslay400 init\n# endregion\n")
        page = write(self.docs / "guides" / "g" / "index.md",
                     "<!-- snippet: examples/e/steps.sh#a -->\n```sh\nslay400 wrong\n```\n")
        self.assertEqual([], checker.check(write=True, root=self.docs))
        self.assertIn("slay400 init", page.read_text(encoding="utf-8"))
        self.assertEqual([], checker.check(write=False, root=self.docs))

    def test_an_unmarked_fence_that_is_not_text_is_reported(self):
        write(self.docs / "guides" / "g" / "index.md", "```json\n{}\n```\n")
        problems = checker.check(write=False, root=self.docs)
        self.assertTrue(any("has no snippet marker" in p for p in problems))

    def test_an_unmarked_text_fence_is_allowed(self):
        write(self.docs / "guides" / "g" / "index.md", "```text\nshape\n```\n")
        self.assertEqual([], checker.check(write=False, root=self.docs))

    def test_a_generated_page_is_not_checked_for_snippets(self):
        write(self.docs / "reference" / "r" / "index.md",
              "<!-- Generated by scripts/docs/x.py. Do not edit by hand. -->\n```json\n{}\n```\n")
        self.assertEqual([], checker.check(write=False, root=self.docs))

    def test_a_missing_snippet_source_is_reported_not_raised(self):
        write(self.docs / "guides" / "g" / "index.md",
              "<!-- snippet: examples/missing/steps.sh#a -->\n```sh\nx\n```\n")
        problems = checker.check(write=False, root=self.docs)
        self.assertTrue(any("could not be read" in p for p in problems))

    def test_write_fixes_two_blocks_that_originally_show_identical_text_independently(self):
        """Regression test: two snippets that both originally show "0 errors, 0 warnings, 0 notes" but resolve
        to DIFFERENT real text must each get their OWN real text, not whichever occurrence a naive text-based
        replace finds first (content-based replacement previously cross-wrote two such blocks on the real
        quickstart page: see the kickoff 16 pull request)."""
        write(self.examples / "e" / "steps.sh",
              "# region: first\nslay400 a\n# endregion\n\n# region: second\nslay400 b\n# endregion\n")
        expected = self.examples / "e" / "expected"
        write(expected / "first.out", "clean\n")
        write(expected / "second.out", "warning\n")
        page = write(self.docs / "guides" / "g" / "index.md",
                     "<!-- snippet: examples/e/expected/first.out -->\n```text\nsame\n```\n\n"
                     "<!-- snippet: examples/e/expected/second.out -->\n```text\nsame\n```\n")
        checker.check(write=True, root=self.docs)
        text = page.read_text(encoding="utf-8")
        snippets = _snippets.snippets_in(text)
        self.assertEqual("clean", snippets[0].shown_body)
        self.assertEqual("warning", snippets[1].shown_body)


if __name__ == "__main__":
    unittest.main()
