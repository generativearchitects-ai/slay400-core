"""Tests of check_front_matter.py. Run with: python3 -m unittest discover -s scripts/docs"""
import tempfile
import unittest
from pathlib import Path

import check_front_matter as checker

GOOD = """---
title: A guide
description: Something useful.
section: guides
slug: a-guide
order: 1
appliesTo: "0.1"
---

# A guide

Some text.
"""


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


class CheckOneTest(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def test_a_well_formed_page_has_no_problems(self):
        page = write(self.root / "guides" / "a-guide" / "index.md", GOOD)
        self.assertEqual([], checker.check_one(page))

    def test_a_missing_required_field_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("description: Something useful.\n", ""))
        problems = checker.check_one(page)
        self.assertTrue(any("missing 'description'" in p for p in problems))

    def test_a_title_longer_than_60_characters_is_reported(self):
        long_title = "title: " + "x" * 61 + "\n"
        page = write(self.root / "p.md", GOOD.replace("title: A guide\n", long_title))
        problems = checker.check_one(page)
        self.assertTrue(any("longer than 60" in p for p in problems))

    def test_a_title_naming_the_product_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("title: A guide\n", "title: slay400 guide\n"))
        problems = checker.check_one(page)
        self.assertTrue(any("names the product" in p for p in problems))

    def test_an_invalid_section_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("section: guides\n", "section: howtos\n"))
        problems = checker.check_one(page)
        self.assertTrue(any("not one of" in p for p in problems))

    def test_a_non_integer_order_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("order: 1\n", "order: first\n"))
        problems = checker.check_one(page)
        self.assertTrue(any("is not an integer" in p for p in problems))

    def test_time_outside_get_started_or_tutorials_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("order: 1\n", "order: 1\ntime: 5 min\n"))
        problems = checker.check_one(page)
        self.assertTrue(any("'time' is only for" in p for p in problems))

    def test_time_is_allowed_for_a_tutorials_page(self):
        text = GOOD.replace("section: guides\n", "section: tutorials\n").replace("order: 1\n", "order: 1\ntime: 5 min\n")
        text += "\nBefore you start, you need nothing.\n"
        page = write(self.root / "p.md", text)
        self.assertEqual([], checker.check_one(page))

    def test_a_page_not_starting_with_a_heading_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("# A guide\n\n", ""))
        problems = checker.check_one(page)
        self.assertTrue(any("does not start with one" in p for p in problems))

    def test_a_generators_comment_before_the_heading_is_skipped(self):
        text = GOOD.replace("# A guide\n", "<!-- Generated by scripts/docs/x.py. Do not edit by hand. -->\n\n# A guide\n")
        page = write(self.root / "p.md", text)
        self.assertEqual([], checker.check_one(page))

    def test_a_heading_that_does_not_equal_the_title_is_reported(self):
        page = write(self.root / "p.md", GOOD.replace("# A guide\n", "# Something else\n"))
        problems = checker.check_one(page)
        self.assertTrue(any("does not equal the title" in p for p in problems))

    def test_get_started_or_tutorials_needs_a_before_you_start_section(self):
        page = write(self.root / "p.md", GOOD.replace("section: guides\n", "section: tutorials\n"))
        problems = checker.check_one(page)
        self.assertTrue(any("'Before you start'" in p for p in problems))

    def test_a_relative_link_is_rejected(self):
        page = write(self.root / "p.md", GOOD + "\nSee [here](../other.md).\n")
        problems = checker.check_one(page)
        self.assertTrue(any("is relative" in p for p in problems))

    def test_a_site_link_an_https_link_and_an_anchor_are_all_accepted(self):
        text = GOOD + "\nSee [a](/docs/guides/b/), [b](https://github.com/x/y) and [c](#section).\n"
        page = write(self.root / "p.md", text)
        self.assertEqual([], checker.check_one(page))


class RawHtmlOutsideCodeTest(unittest.TestCase):
    """kickoff 19: the website's rule, applied here so the next case fails on this repository's own check."""

    def test_a_bare_tag_like_sequence_in_prose_is_found(self):
        self.assertEqual(["<value>"], checker.raw_html_outside_code("API <value> is new in version."))

    def test_a_bare_comment_open_in_prose_is_found(self):
        found = checker.raw_html_outside_code("Something odd: <!-- not a real comment")
        self.assertIn("<!--", found)

    def test_an_ampersand_shaped_reference_is_not_this_checks_job(self):
        # & alone is not tag-shaped; escaping & is the generators' job (generate_schema_reference.escape_prose),
        # not something this check flags on its own.
        self.assertEqual([], checker.raw_html_outside_code("a literal, or ${environment.name} & more"))

    def test_a_snippet_marker_is_allowed(self):
        text = "before\n<!-- snippet: examples/e/steps.sh#a -->\n```sh\nx\n```\nafter"
        self.assertEqual([], checker.raw_html_outside_code(text))

    def test_the_one_generated_by_comment_is_allowed(self):
        text = "<!-- Generated by scripts/docs/generate_x.py from y. Do not edit by hand. -->\n\n# Heading\n"
        self.assertEqual([], checker.raw_html_outside_code(text))

    def test_an_autolink_is_allowed(self):
        text = "See <https://example.com/path> for more."
        self.assertEqual([], checker.raw_html_outside_code(text))

    def test_tag_like_text_inside_a_fenced_block_is_allowed(self):
        text = "It prints:\n\n```text\nAPI <value> is new\n```\n"
        self.assertEqual([], checker.raw_html_outside_code(text))

    def test_tag_like_text_inside_an_inline_code_span_is_allowed(self):
        text = "The point marked `<value>` is filled in at run time."
        self.assertEqual([], checker.raw_html_outside_code(text))

    def test_a_page_with_a_bare_placeholder_in_prose_is_rejected_by_check_one(self):
        page = write(Path(tempfile.mkdtemp()) / "p.md", GOOD + "\nIt prints: > API <value> is new.\n")
        problems = checker.check_one(page)
        self.assertTrue(any("raw HTML" in p for p in problems))

    def test_a_page_with_the_same_placeholder_only_inside_code_is_accepted(self):
        page = write(Path(tempfile.mkdtemp()) / "p.md", GOOD + "\nIt prints:\n\n```text\nAPI <value> is new\n```\n")
        self.assertEqual([], checker.check_one(page))


class CheckTest(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def test_two_pages_with_the_same_slug_in_the_same_section_conflict(self):
        write(self.root / "guides" / "a" / "index.md", GOOD)
        write(self.root / "guides" / "b" / "index.md", GOOD)
        problems = checker.check(self.root)
        self.assertTrue(any("is used by more than one page" in p for p in problems))

    def test_the_same_slug_in_different_sections_does_not_conflict(self):
        write(self.root / "guides" / "a" / "index.md", GOOD)
        write(self.root / "concepts" / "a" / "index.md", GOOD.replace("section: guides\n", "section: concepts\n"))
        problems = checker.check(self.root)
        self.assertEqual([], [p for p in problems if "more than one page" in p])


if __name__ == "__main__":
    unittest.main()
