"""Generates docs/reference/cli/index.md from the tool's own --help and help <command> output (specs/documentation.md
section 7), by running the packaged jar directly (no launcher needed to read help text).

Usage: generate_cli_reference.py [--check]
--check regenerates into memory and fails if it differs from the committed file, instead of writing it.

Needs Python 3, Java 21, and the jar pcml-cli just built (pcml-cli/target/pcml-cli-*.jar): run
`./mvnw -pl pcml-cli -am package -DskipTests` first (or the whole ./mvnw verify).

Exit code 0: written (or, with --check, already current). 1: the jar is missing, or --check found it stale.
"""
import argparse
import glob
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
TARGET = REPO / "docs" / "reference" / "cli" / "index.md"
COMMANDS = ["init", "annotate", "validate", "generate", "bundle", "diff", "gateway"]


def find_jar() -> Path:
    candidates = [p for p in glob.glob(str(REPO / "pcml-cli" / "target" / "pcml-cli-*.jar"))
                  if "sources" not in p and "javadoc" not in p]
    if not candidates:
        raise FileNotFoundError("pcml-cli/target/pcml-cli-*.jar was not found; build it first")
    return Path(candidates[0])


def run(jar: Path, *args: str) -> str:
    result = subprocess.run(["java", "-jar", str(jar), *args], capture_output=True, text=True, timeout=30)
    return result.stdout


FRONT_MATTER = """---
title: Command-line reference
description: Every command, option, default and exit status of slay400, from its own --help.
section: reference
slug: cli
order: 10
appliesTo: "0.1"
---
"""


def render(jar: Path) -> str:
    out = [FRONT_MATTER.rstrip("\n"), "",
           "<!-- Generated by scripts/docs/generate_cli_reference.py from the tool's own --help output. Do not edit by hand. -->",
           "", "# Command-line reference", "",
           "The output of `slay400 --help` and `slay400 help <command>`, for every command.", "",
           "## General", "", "```", run(jar, "--help").rstrip("\n"), "```", ""]
    for command in COMMANDS:
        out += [f"## `{command}`", "", "```", run(jar, "help", command).rstrip("\n"), "```", ""]
    return "\n".join(out) + "\n"


def main(argv):
    parser = argparse.ArgumentParser(description="Generates the command-line reference from the tool's own help.")
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale, instead of writing it")
    args = parser.parse_args(argv)
    try:
        jar = find_jar()
    except FileNotFoundError as e:
        print("FAIL: " + str(e))
        return 1
    rendered = render(jar)
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None
        if current != rendered:
            print(f"FAIL: {TARGET} is stale; run scripts/docs/generate_cli_reference.py")
            return 1
        print("OK: the command-line reference is current")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
