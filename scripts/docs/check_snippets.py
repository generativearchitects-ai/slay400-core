#!/usr/bin/env python3
"""docs:snippets (specs/documentation.md section 5, kickoff 16): every marked code block in a page must be exactly
the text of the example file (or region) it names. A fenced code block with no marker is an error, except one
fenced as "text" (a shape, not a real output -- whether the sentence before it actually says so is not checked
here: that is prose, not something a script can verify).

Usage: check_snippets.py [--write]
--write rewrites every marked block from its source instead of reporting a mismatch.

Needs Python 3 and nothing else. Exit code 0: every block matches (or was rewritten). 1: problems, one per line.
"""
import argparse
import sys
from pathlib import Path

import _pages
import _snippets


def check(write: bool, root: Path | None = None) -> list[str]:
    problems = []
    for page in (_pages.pages(root) if root is not None else _pages.pages()):
        text = page.read_text(encoding="utf-8")
        if "<!-- Generated by scripts/docs/" in text:
            continue  # a generated reference page is kept honest by its own generator's staleness check instead
        edits = []  # (start, end, replacement); applied back-to-front so earlier spans stay valid
        for snippet in _snippets.snippets_in(text):
            try:
                actual = _snippets.resolve(snippet.source, snippet.region)
            except (FileNotFoundError, KeyError) as e:
                problems.append(f"{page}: snippet source {snippet.source}"
                                 f"{'#' + snippet.region if snippet.region else ''} could not be read: {e}")
                continue
            if snippet.shown_body != actual:
                if write:
                    edits.append((*snippet.span, actual))
                else:
                    name = snippet.source + (f"#{snippet.region}" if snippet.region else "")
                    problems.append(f"{page}: the block for {name} does not match its source")
        for lang in _snippets.unmarked_fences(text):
            if lang.strip() != "text":
                problems.append(f"{page}: a {lang or '(no language)'} code block has no snippet marker")
        if write and edits:
            changed = text
            for start, end, replacement in sorted(edits, reverse=True):
                changed = changed[:start] + replacement + changed[end:]
            page.write_text(changed, encoding="utf-8")
    return problems


def main(argv):
    parser = argparse.ArgumentParser(description="Checks that every marked code block matches its example source.")
    parser.add_argument("--write", action="store_true", help="rewrite blocks from their source instead of failing")
    args = parser.parse_args(argv)
    problems = check(args.write)
    for problem in problems:
        print("FAIL: " + problem)
    if problems:
        print(f"{len(problems)} problem(s)")
        return 1
    print("OK: every snippet matches its source")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
