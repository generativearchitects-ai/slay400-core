"""Generates the api.yaml and repository-defaults reference pages from the JSON Schemas pcml-overlay publishes
(specs/documentation.md section 7), with a complete example of each from docs/reference/_notes/.

Usage: generate_schema_reference.py [--check]

Needs Python 3 and nothing else. Exit code 0: written (or, with --check, already current). 1: --check found a
page stale, or an example file is missing.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
SCHEMAS = REPO / "pcml-overlay" / "src" / "main" / "resources" / "ai" / "generativearchitects" / "slay400" / "pcml" / "overlay"
NOTES = REPO / "docs" / "reference" / "_notes"

PAGES = [
    {
        "schema": SCHEMAS / "api.schema.json",
        "target": REPO / "docs" / "reference" / "api-yaml" / "index.md",
        "example": NOTES / "api-yaml" / "example.yaml",
        "front_matter": """---
title: api.yaml reference
description: Every field of the overlay file, from its JSON Schema, with a complete example.
section: reference
slug: api-yaml
order: 20
appliesTo: "0.1"
---
""",
        "heading": "api.yaml reference",
        "intro": "The overlay file, one per folder under `apis/`: the API contract (direction, semantic types, exposed names and more)"
                 " over the PCML call contract. Generated from its JSON Schema.",
    },
    {
        "schema": SCHEMAS / "gateway.schema.json",
        "target": REPO / "docs" / "reference" / "repository-defaults" / "index.md",
        "example": NOTES / "repository-defaults" / "example.yaml",
        "front_matter": """---
title: Repository defaults reference
description: Every field of gateway.yaml, the repository defaults file, from its JSON Schema, with a complete example.
section: reference
slug: repository-defaults
order: 21
appliesTo: "0.1"
---
""",
        "heading": "Repository defaults reference",
        "intro": "The repository defaults file, `gateway.yaml`, at the root of a repository of APIs: defaults every overlay file can"
                 " override. Not the gateway's own configuration file, also called `gateway.yaml` by its README; see the words and"
                 " names rule of the documentation spec, section 9. Generated from its JSON Schema.",
    },
]


def resolve(node, defs):
    if isinstance(node, dict) and "$ref" in node:
        name = node["$ref"].removeprefix("#/$defs/")
        return resolve(defs[name], defs)
    return node


def rows(properties: dict, defs: dict, prefix: str = "") -> list[tuple[str, str, str]]:
    out = []
    for name, raw in properties.items():
        node = resolve(raw, defs)
        kind = node.get("type") or node.get("enum") or ("one of several forms" if "oneOf" in node else "")
        if isinstance(kind, list):
            kind = " or ".join(str(k) for k in kind)
        description = node.get("description", "")
        out.append((prefix + name, str(kind), description))
        nested = node.get("properties")
        if nested:
            out.extend(rows(nested, defs, prefix + name + "."))
    return out


def render(page: dict) -> str:
    schema = json.loads(page["schema"].read_text(encoding="utf-8"))
    defs = schema.get("$defs", {})
    table_rows = rows(schema.get("properties", {}), defs)
    lines = [page["front_matter"].rstrip("\n"), "",
              f"<!-- Generated by scripts/docs/generate_schema_reference.py from {page['schema'].relative_to(REPO)}."
              " Do not edit by hand. -->",
              "", f"# {page['heading']}", "", page["intro"], "", "## Fields", "", "| Field | Type | Description |", "|---|---|---|"]
    for name, kind, description in table_rows:
        lines.append(f"| `{name}` | {kind} | {description} |")
    lines += ["", schema.get("description", ""), "", "## Complete example", "", "```yaml",
              page["example"].read_text(encoding="utf-8").rstrip("\n"), "```", ""]
    return "\n".join(lines) + "\n"


def main(argv):
    parser = argparse.ArgumentParser(description="Generates the api.yaml and repository-defaults reference pages.")
    parser.add_argument("--check", action="store_true", help="fail if stale, instead of writing")
    args = parser.parse_args(argv)
    problems = []
    for page in PAGES:
        if not page["example"].is_file():
            problems.append(f"{page['example']} is missing (a complete, hand-written example)")
            continue
        rendered = render(page)
        if args.check:
            current = page["target"].read_text(encoding="utf-8") if page["target"].is_file() else None
            if current != rendered:
                problems.append(f"{page['target']} is stale; run scripts/docs/generate_schema_reference.py")
            continue
        page["target"].parent.mkdir(parents=True, exist_ok=True)
        page["target"].write_text(rendered, encoding="utf-8")
        print(f"Wrote {page['target']}")
    for problem in problems:
        print("FAIL: " + problem)
    if problems:
        print(f"{len(problems)} problem(s)")
        return 1
    if args.check:
        print("OK: both schema reference pages are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
