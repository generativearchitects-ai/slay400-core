"""Tests of generate_schema_reference.py. Run with: python3 -m unittest discover -s scripts/docs"""
import unittest

import generate_schema_reference as gen


class ResolveTest(unittest.TestCase):

    def test_a_node_with_no_ref_is_returned_as_is(self):
        node = {"type": "string"}
        self.assertEqual(node, gen.resolve(node, {}))

    def test_a_ref_is_followed_into_defs(self):
        defs = {"Thing": {"type": "object", "properties": {"a": {"type": "string"}}}}
        node = {"$ref": "#/$defs/Thing"}
        self.assertEqual(defs["Thing"], gen.resolve(node, defs))


class RowsTest(unittest.TestCase):

    def test_a_plain_property_becomes_one_row(self):
        properties = {"name": {"type": "string", "description": "a name"}}
        self.assertEqual([("name", "string", "a name")], gen.rows(properties, {}))

    def test_an_enum_property_shows_its_values_joined_with_or(self):
        properties = {"method": {"enum": ["GET", "POST"]}}
        self.assertEqual([("method", "GET or POST", "")], gen.rows(properties, {}))

    def test_a_oneof_property_is_shown_as_one_of_several_forms(self):
        properties = {"call": {"oneOf": [{"type": "string"}, {"type": "object"}]}}
        self.assertEqual([("call", "one of several forms", "")], gen.rows(properties, {}))

    def test_nested_properties_are_recursed_into_with_a_dotted_prefix(self):
        properties = {"error": {"type": "object", "properties": {"code": {"type": "string"}}}}
        self.assertEqual(
            [("error", "object", ""), ("error.code", "string", "")],
            gen.rows(properties, {}))

    def test_a_ref_property_is_resolved_before_its_row_is_built(self):
        defs = {"When": {"type": "object", "description": "a condition"}}
        properties = {"when": {"$ref": "#/$defs/When"}}
        self.assertEqual([("when", "object", "a condition")], gen.rows(properties, defs))


class RenderTest(unittest.TestCase):

    def test_render_includes_the_front_matter_heading_table_and_example(self, ):
        import json
        import tempfile
        from pathlib import Path
        real_repo = gen.REPO
        with tempfile.TemporaryDirectory() as tmp:
            gen.REPO = Path(tmp)  # render() computes the schema's path relative to REPO for its "generated by" comment
            self.addCleanup(lambda: setattr(gen, "REPO", real_repo))
            schema_path = Path(tmp) / "s.json"
            schema_path.write_text(json.dumps({
                "description": "A schema.",
                "properties": {"name": {"type": "string", "description": "a name"}},
            }), encoding="utf-8")
            example_path = Path(tmp) / "example.yaml"
            example_path.write_text("name: foo\n", encoding="utf-8")
            page = {
                "schema": schema_path,
                "example": example_path,
                "front_matter": "---\ntitle: T\n---\n",
                "heading": "T",
                "intro": "An intro.",
            }
            rendered = gen.render(page)
        self.assertIn("title: T", rendered)
        self.assertIn("# T", rendered)
        self.assertIn("An intro.", rendered)
        self.assertIn("| `name` | string | a name |", rendered)
        self.assertIn("A schema.", rendered)
        self.assertIn("name: foo", rendered)
        self.assertIn("Do not edit by hand", rendered)


if __name__ == "__main__":
    unittest.main()
